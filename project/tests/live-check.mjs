import path from 'node:path';
import puppeteer from 'puppeteer-core';
const URL_ = process.argv[2];
const SAMPLE = process.argv[3] || 'samples/license_perspective_glare_clutter.jpg';
const b = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
const p = await b.newPage();
await p.setViewport({ width: 412, height: 915, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto(URL_, { waitUntil: 'networkidle0' });
await (await p.$('#inFile')).uploadFile(path.resolve(SAMPLE));
await p.waitForFunction(() => !document.getElementById('btnExtract').disabled, { timeout: 30000 });
await p.click('#btnExtract');
await p.waitForSelector('#step5:not(.hidden)', { timeout: 180000 });
const out = await p.$eval('#outText', t => t.value);
const sw = await p.evaluate(async () => !!(await navigator.serviceWorker.getRegistration()));
const swVer = await p.evaluate(async () => (await (await fetch('sw.js', { cache: 'no-store' })).text()).match(/grx-scan-v\d+/)?.[0]);
console.log('Sample:', SAMPLE, '| SW cache:', swVer);
console.log(out.split('\n').slice(0, 30).join('\n')); console.log('SW registered:', sw, 'errors:', errs);
await b.close();
